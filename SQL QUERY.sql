-- Q.1 WRITE A SQL QUERY TO RETRIEVE ALL COLUMNS FOR SALES MADE ON '2022-11-05
SELECT *
FROM RETAIL
WHERE SALE_DATE = '2022-11-05' ;


-- Q.2 WRITE A SQL QUERY TO RETRIEVE ALL TRANSACTIONS WHERE THE CATEGORY IS 'CLOTHING' AND 
-- THE QUANTITY SOLD IS MORE THAN 10 IN THE MONTH OF NOV-2022
SELECT * 
FROM RETAIL
WHERE CATEGORY = 'Clothing' 
AND  QUANTIY > 10
AND  SALE_DATE BETWEEN '2022-11-01' AND '2022-11-30' ;


-- Q.3 WRITE A SQL QUERY TO CALCULATE THE TOTAL SALES (TOTAL_SALE) FOR EACH CATEGORY.
SELECT 
   CATEGORY,
   SUM(TOTAL_SALE) AS CATEGORY_SALES
FROM RETAIL
GROUP BY CATEGORY 
ORDER BY CATEGORY_SALES DESC;


-- Q.4 WRITE A SQL QUERY TO FIND THE AVERAGE AGE OF CUSTOMERS WHO PURCHASED ITEMS FROM THE 'BEAUTY' CATEGORY.
SELECT 
   CATEGORY,
   ROUND(AVG(AGE),2) AS AVERAGE_AGE
FROM RETAIL
GROUP BY CATEGORY
HAVING CATEGORY = 'Beauty' ;
    


-- Q.5 WRITE A SQL QUERY TO FIND ALL TRANSACTIONS WHERE THE TOTAL_SALE IS GREATER THAN 1000.
SELECT * 
FROM RETAIL 
WHERE TOTAL_SALE > 1000 
ORDER BY SALE_DATE ;


-- Q.6 WRITE A SQL QUERY TO FIND THE TOTAL NUMBER OF TRANSACTIONS (TRANSACTION_ID) MADE BY EACH GENDER IN EACH CATEGORY.
SELECT 
    CATEGORY,
	GENDER,
	COUNT(TRANSACTIONS_ID) AS TOTAL_RECORD
FROM RETAIL 
GROUP BY CATEGORY,
	     GENDER
ORDER BY 1 ;		 


-- Q.7 WRITE A SQL QUERY TO CALCULATE THE AVERAGE SALE FOR EACH MONTH. FIND OUT BEST SELLING MONTH IN EACH YEAR
WITH MONTHLY_AVG AS 
(SELECT 
    TO_CHAR(SALE_DATE,'YYYY') AS YEAR,
	EXTRACT(MONTH FROM SALE_DATE) AS MONTH_NUMBER,
	ROUND(AVG(TOTAL_SALE),2) MONTHLY_AVG,
	SUM(TOTAL_SALE) AS MONTHLY_SALE
FROM RETAIL
GROUP BY
    TO_CHAR(SALE_DATE,'YYYY'),
	EXTRACT(MONTH FROM SALE_DATE) ),
RANKING AS (
SELECT *,
       ROW_NUMBER() OVER(PARTITION BY YEAR 
	ORDER BY MONTHLY_AVG DESC) AS RANKING
FROM MONTHLY_AVG	
)
SELECT * FROM RANKING
WHERE RANKING= 1
;


-- Q.8 WRITE A SQL QUERY TO FIND THE TOP 5 CUSTOMERS BASED ON THE HIGHEST TOTAL SALES 
SELECT CUSTOMER_ID,
       SUM(TOTAL_SALE) AS CUSTOMER_SALE
FROM RETAIL
GROUP BY CUSTOMER_ID
ORDER BY CUSTOMER_SALE DESC
LIMIT 5 ;


-- Q.9 WRITE A SQL QUERY TO FIND THE NUMBER OF UNIQUE CUSTOMERS WHO PURCHASED ITEMS FROM EACH CATEGORY.
SELECT 
     CATEGORY,
	 COUNT(DISTINCT CUSTOMER_ID) AS CUSTOMERS
FROM RETAIL
GROUP BY CATEGORY ;


-- Q.10 WRITE A SQL QUERY TO CREATE EACH SHIFT AND NUMBER OF ORDERS (EXAMPLE MORNING <=12, AFTERNOON BETWEEN 12 & 17, EVENING >17)
SELECT
CASE
WHEN EXTRACT(HOUR FROM sale_time) <= 12 THEN 'Morning'
WHEN EXTRACT(HOUR FROM sale_time) BETWEEN 12 AND 16 THEN 'Afternoon'
ELSE 'Evening'
END AS shift,
COUNT(*) AS number_of_orders
FROM retail
GROUP BY 1
ORDER BY 2 DESC;
 
    

