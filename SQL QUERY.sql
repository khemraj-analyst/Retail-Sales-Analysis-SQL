-- MONTHLY SALES
SELECT 
    DATE_TRUNC('MONTH',SALE_DATE) AS MONTH,
	SUM(TOTAL_SALE) MONTHLY_SALES
FROM RETAIL
GROUP BY DATE_TRUNC('MONTH',SALE_DATE)
ORDER BY MONTH ;

-- MONTH WITH HIGHEST SALES 
SELECT 
    DATE_TRUNC('MONTH',SALE_DATE)::DATE AS MONTH,
	SUM(TOTAL_SALE) MONTHLY_SALES
FROM RETAIL
GROUP BY DATE_TRUNC('MONTH',SALE_DATE)
ORDER BY MONTH DESC
LIMIT 1;

-- MONTH_OVER_MONTH(MOM) SALES GROWTH
WITH MONTHLY_SALES AS(
SELECT 
  DATE_TRUNC('MONTH',SALE_DATE) AS MONTH,
  SUM(TOTAL_SALE) AS MONTHLY_SALES
FROM RETAIL
GROUP BY DATE_TRUNC('MONTH',SALE_DATE)
ORDER BY MONTH
),
PREVIOUS_MONTH_SALE AS(
SELECT 
   MONTH,
   MONTHLY_SALES,
   LAG(MONTHLY_SALES) OVER(ORDER BY MONTH)
   AS PREVIOUS_MONTH_SALE
FROM MONTHLY_SALES   
)
SELECT *,
    ROUND((MONTHLY_SALES - PREVIOUS_MONTH_SALE) /
	NULLIF(PREVIOUS_MONTH_SALE,0) * 100.0 ,2)
	AS MOM_GROWTH
FROM PREVIOUS_MONTH_SALE
ORDER BY MONTH ;


-- YEARLY SALES
SELECT 
    DATE_TRUNC('YEAR',SALE_DATE) AS YEAR,
	SUM(TOTAL_SALE) MONTHLY_SALES
FROM RETAIL
GROUP BY DATE_TRUNC('YEAR',SALE_DATE)
ORDER BY YEAR ;


