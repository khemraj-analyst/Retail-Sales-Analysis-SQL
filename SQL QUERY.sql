-- CREATE TABLE RETAIL
CREATE TABLE IF NOT EXISTS RETAIL(
TRANSACTIONS_ID SERIAL PRIMARY KEY,
SALE_DATE DATE,
SALE_TIME TIME,
CUSTOMER_ID INT,
GENDER VARCHAR(150),
AGE INT,
CATEGORY VARCHAR(150),
QUANTIY INT,
PRICE_PER_UNIT INT,
COGS NUMERIC(5,2),
TOTAL_SALE NUMERIC(8,2)
);

